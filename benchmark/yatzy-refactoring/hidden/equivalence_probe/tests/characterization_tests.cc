TEST(YatzyCharacterization, AllScoresMatchRecordedResults) {
    for (std::size_t i = 0; i < sizeof(kYatzyCharacterizationRows) / sizeof(kYatzyCharacterizationRows[0]); ++i) {
        const Row& r = kYatzyCharacterizationRows[i];
        int dice[5] = {r.d[0], r.d[1], r.d[2], r.d[3], r.d[4]};
        Yatzy1 y(r.d[0], r.d[1], r.d[2], r.d[3], r.d[4]);
        EXPECT_EQ(r.chance, Yatzy1::Chance(r.d[0], r.d[1], r.d[2], r.d[3], r.d[4])) << i;
        EXPECT_EQ(r.yatzy, Yatzy1::yatzy(dice)) << i;
        EXPECT_EQ(r.ones, Yatzy1::Ones(r.d[0], r.d[1], r.d[2], r.d[3], r.d[4])) << i;
        EXPECT_EQ(r.twos, Yatzy1::Twos(r.d[0], r.d[1], r.d[2], r.d[3], r.d[4])) << i;
        EXPECT_EQ(r.threes, Yatzy1::Threes(r.d[0], r.d[1], r.d[2], r.d[3], r.d[4])) << i;
        EXPECT_EQ(r.fours, y.Fours()) << i;
        EXPECT_EQ(r.fives, y.Fives()) << i;
        EXPECT_EQ(r.sixes, y.sixes()) << i;
        EXPECT_EQ(r.pair, y.ScorePair(r.d[0], r.d[1], r.d[2], r.d[3], r.d[4])) << i;
        EXPECT_EQ(r.twoPair, Yatzy1::TwoPair(r.d[0], r.d[1], r.d[2], r.d[3], r.d[4])) << i;
        EXPECT_EQ(r.fourKind, Yatzy1::FourOfAKind(r.d[0], r.d[1], r.d[2], r.d[3], r.d[4])) << i;
        EXPECT_EQ(r.threeKind, Yatzy1::ThreeOfAKind(r.d[0], r.d[1], r.d[2], r.d[3], r.d[4])) << i;
        EXPECT_EQ(r.smallStraight, Yatzy1::SmallStraight(r.d[0], r.d[1], r.d[2], r.d[3], r.d[4])) << i;
        EXPECT_EQ(r.largeStraight, Yatzy1::LargeStraight(r.d[0], r.d[1], r.d[2], r.d[3], r.d[4])) << i;
        EXPECT_EQ(r.fullHouse, Yatzy1::FullHouse(r.d[0], r.d[1], r.d[2], r.d[3], r.d[4])) << i;
    }
}
